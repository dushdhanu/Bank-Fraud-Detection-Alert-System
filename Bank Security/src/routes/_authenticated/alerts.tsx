import { createFileRoute } from "@tanstack/react-router";
import { useQuery } from "@tanstack/react-query";
import { useServerFn } from "@tanstack/react-start";
import { AppShell, Panel } from "@/components/AppShell";
import { SeverityBadge } from "@/components/SeverityBadge";
import { getAlerts } from "@/lib/fraud.functions";
import { ago, maskAccount, type Severity } from "@/lib/format";

export const Route = createFileRoute("/_authenticated/alerts")({
  head: () => ({
    meta: [
      { title: "Alert Log — Sentinel Risk Ops" },
      {
        name: "description",
        content:
          "Account-holder and admin notifications generated by high and critical risk transactions.",
      },
      { property: "og:title", content: "Alert Log — Sentinel Risk Ops" },
      {
        property: "og:description",
        content: "Every fraud notification sent, with channel, recipient and delivery state.",
      },
      { property: "og:type", content: "website" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: AlertsPage,
});

function AlertsPage() {
  const alertsFn = useServerFn(getAlerts);
  const { data } = useQuery({ queryKey: ["alerts"], queryFn: () => alertsFn({}) });
  const alerts = data ?? [];

  return (
    <AppShell
      title="Alert log"
      subtitle="Notifications raised for high and critical severity activity."
    >
      <Panel title={`Alerts · ${alerts.length}`}>
        <ul className="divide-y divide-border">
          {alerts.map((a) => (
            <li key={a.id} className="flex flex-wrap items-start gap-3 px-4 py-3">
              <SeverityBadge severity={a.severity as Severity} />
              <div className="min-w-0 flex-1">
                <p className="text-sm text-foreground">{a.message}</p>
                <p className="mt-1 font-mono text-[11px] text-muted-foreground">
                  {a.channel} → {a.recipient} ·{" "}
                  {a.accounts ? maskAccount(a.accounts.account_number) : "—"} · {ago(a.created_at)}{" "}
                  ago · {a.delivered ? "delivered" : "queued"}
                </p>
              </div>
            </li>
          ))}
          {alerts.length === 0 ? (
            <li className="px-4 py-6 text-sm text-muted-foreground">No alerts raised.</li>
          ) : null}
        </ul>
      </Panel>
    </AppShell>
  );
}
